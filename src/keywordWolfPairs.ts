export const KEYWORD_WOLF_PAIRS: readonly KeywordWolfPair[] = GROUPS.flatMap((group) =>
  group.slice(0, -1).map((majority, index) => ({ majority, wolf: group[index + 1] })),
);

export function randomKeywordWolfPair(random: () => number = Math.random): KeywordWolfPair {
  const pair = KEYWORD_WOLF_PAIRS[Math.floor(random() * KEYWORD_WOLF_PAIRS.length)] ?? KEYWORD_WOLF_PAIRS[0];
  return random() < 0.5 ? pair : { majority: pair.wolf, wolf: pair.majority };
}
